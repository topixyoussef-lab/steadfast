/**
 * Translation dictionaries.
 *
 * `en` is the source of truth. `ar` is typed against it, so a missing or extra
 * key is a compile error rather than an English string leaking into the Arabic
 * interface at runtime.
 */

/**
 * Strips `as const` literal types so the Arabic dictionary is checked against
 * the shape of the English one (keys present, values are plain strings) rather
 * than against its literal values. Readonly-ness is preserved, because `en` is
 * declared `as const` and the exported `dictionaries` record holds both.
 */
type Widen<T> = {
  readonly [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends readonly string[]
      ? readonly string[]
      : Widen<T[K]>;
};

